/**
 * The ONE copy of our legal text.
 *
 * It used to live only inside the web Blade templates, which meant the mobile app could only show
 * it by loading netwix.online/terms in a WebView — and that page carries the full site chrome. Its
 * footer alone has 28 internal links (/movies, /series, /anime, /genre/*, /login, …), all of which
 * the WebView happily followed, so tapping one dropped the viewer into the *website* inside the app
 * with no way back to the app's own navigation (owner, 2026-08-16: "ในแอพมันจะทำให้คนไปเล่นในหน้าเว็บแทน
 * สับสนหมด"). The app now renders this text natively instead, so there is no page to wander off.
 *
 * Keeping the text HERE rather than copying it into the app is the point: legal copy that exists
 * twice drifts, and then the two surfaces promise users different things.
 *
 * Format is the same plain-text markup the admin CMS already accepts, so one renderer serves both:
 *   "## " starts a heading, "- " a bullet, blank lines separate paragraphs.
 * An admin-authored body (Setting legal_terms_body / legal_privacy_body) overrides the built-in
 * text for web and app alike.
 */
class LegalDocs
{
    public const DOCS = ['terms', 'privacy'];

    /** Shown as "ปรับปรุงล่าสุด" when no admin override sets its own date. */
    public const UPDATED = '3 กรกฎาคม 2568';

    public static function title(string $doc): string
    {
        return $doc === 'privacy' ? 'นโยบายความเป็นส่วนตัว' : 'ข้อตกลงและเงื่อนไขการใช้งาน';
    }

    public static function updated(): string
    {
        return (string) (Setting::get('legal_updated_at') ?: self::UPDATED);
    }

    /** The document body in CMS markup — admin override first, built-in text otherwise. */
    public static function body(string $doc): string
    {
        $custom = trim((string) Setting::get($doc === 'privacy' ? 'legal_privacy_body' : 'legal_terms_body'));

        return $custom !== '' ? $custom : self::builtIn($doc);
    }

    /**
     * The body as structured blocks, for clients that render it themselves rather than as HTML.
     *
     * @return array<int,array{type:string,text:string}>  type: heading|paragraph|bullet
     */
    public static function blocks(string $doc): array
    {
        $blocks = [];
        foreach (preg_split('/
||
/', self::body($doc)) as $line) {
            $line = trim($line);
            if ($line === '') {
                continue;
            }
            if (str_starts_with($line, '## ')) {
                $blocks[] = ['type' => 'heading', 'text' => trim(substr($line, 3))];
            } elseif (str_starts_with($line, '- ')) {
                $blocks[] = ['type' => 'bullet', 'text' => trim(substr($line, 2))];
            } else {
                $blocks[] = ['type' => 'paragraph', 'text' => $line];
            }
        }

        return $blocks;
    }

    private static function builtIn(string $doc): string
    {
        return $doc === 'privacy' ? self::PRIVACY : self::TERMS;
    }

